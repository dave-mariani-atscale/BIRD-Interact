#!/usr/bin/env python3
"""Regenerate results/v12_round2_ledger.tsv from the sheet's R2- rows.

The SHEET IS CANONICAL.  This file is a derived mirror and nothing should ever
edit it by hand: it exists so a round-2 session can rank ~50 deferred levers
across 20 databases in one read without paying for a sheet round-trip per row.
Because it is generated, it cannot drift -- if it disagrees with the sheet, the
sheet is right and you regenerate.

    python3 scripts/r2_ledger.py            # rewrite the mirror, print a summary
    python3 scripts/r2_ledger.py --rank     # also print the ranking round 2 opens with

A row qualifies for an R2- id only if it carries all four of: a named mechanism,
a falsifiable prediction (which tasks, what they would score), the result of a
$0 gold_diff sweep already attempted, and a cost estimate in runs.  See the
ROUND-2 LEDGER block in results/kickoff_00_v12_order.md.
"""
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "results" / "v12_round2_ledger.tsv"
COLS = ["ID", "Issue", "Brief", "Fix needed in", "Status", "Priority",
        "Tasks affected", "Impact", "Repro / evidence", "Found in run", "Notes"]


def main():
    raw = subprocess.run([sys.executable, str(HERE / "sheet.py"), "read"],
                         capture_output=True, text=True, check=True).stdout
    lines = raw.splitlines()
    header = lines[0].split("\t")
    idx = {name: i for i, name in enumerate(header)}
    missing = [c for c in COLS if c not in idx]
    if missing:
        sys.exit(f"sheet is missing columns {missing} -- schema changed, fix COLS")

    rows = []
    for line in lines[1:]:
        cells = line.split("\t")
        if len(cells) <= idx["ID"]:
            continue
        if re.match(r"^R2-\d+$", cells[idx["ID"]].strip()):
            rows.append([cells[idx[c]].strip() if idx[c] < len(cells) else "" for c in COLS])

    rows.sort(key=lambda r: int(r[0].split("-")[1]))
    OUT.parent.mkdir(exist_ok=True)
    with OUT.open("w") as fh:
        fh.write("# GENERATED by scripts/r2_ledger.py from the sheet. Do not edit; regenerate.\n")
        fh.write("\t".join(COLS) + "\n")
        for r in rows:
            fh.write("\t".join(c.replace("\t", " ") for c in r) + "\n")

    open_rows = [r for r in rows if r[COLS.index("Status")] == "open"]
    print(f"{OUT.relative_to(HERE.parent)}: {len(rows)} R2 rows, {len(open_rows)} still open")
    by_db = {}
    for r in rows:
        db = r[COLS.index("Brief")].split()[0] if r[COLS.index("Brief")] else "?"
        by_db[db] = by_db.get(db, 0) + 1
    for db, n in sorted(by_db.items(), key=lambda kv: -kv[1]):
        print(f"  {n:>2}  {db}")

    if "--rank" in sys.argv:
        print("\nOpen items, P-order then id -- sweep every one at $0 before spending:")
        for r in sorted(open_rows, key=lambda r: (r[COLS.index("Priority")], int(r[0].split("-")[1]))):
            print(f"  {r[0]:<7} {r[COLS.index('Priority')]:<3} {r[COLS.index('Issue')][:120]}")


if __name__ == "__main__":
    main()
