#!/usr/bin/env bash
# One launcher for the three Snowflake scenarios (2026-11-20), the Genie One scenarios repeated on Snowflake.
# In each, the BIRD agent hands every question to a Cortex Agent grounded in the task database's Cortex Sense
# context and submits the SQL that agent ran; they differ only in what the scenario's role can read:
#
#   1 | cortex-sense-raw           : Cortex Sense on raw data, no Semantic Views   (backend sf_cortex_sense_raw,
#                                    role BIRD_S1: the 244 base tables of BIRD_BENCH)
#   2 | cortex-sense-coco-views    : Cortex Sense + Cortex Code-generated Semantic Views (sf_cortex_sense_coco_views,
#                                    role BIRD_S2: base tables + the 83 views in BIRD_SENSE.COCO_<DB>)
#   3 | cortex-sense-atscale-views : Cortex Sense + AtScale-generated Semantic Views (sf_cortex_sense_atscale_views,
#                                    role BIRD_S3)
#
# Matched to the Genie One runs and the 2026-09-10 AtScale n=3 sweep: Sonnet 5 agent and simulator, a-interact,
# all 410 Query tasks, non-leaderboard corrected grading, default LLM routing, and the same instruction with only
# the tool words rewritten (config/environment_backends.snowflake_vs_0910.yaml, generated by
# scripts/gen_snowflake_backends.py). Runs on this checkout's .env service ports, which must not be 6000-6002.
#
#   bash scripts/run_snowflake_scenario.sh 1                     # foreground, one repetition
#   REPEAT=3 bash scripts/run_snowflake_scenario.sh 1            # three repetitions, back to back
#   DATABASES=solar_panel LIMIT=2 bash scripts/run_snowflake_scenario.sh smoke   # wiring test as the build role
#
# Writes results/<backend>_vs_0910/<backend>[_runNN]_<stamp>.json, live_compare.txt (every 10 min) and
# final_compare[_runNN].txt. Do not reprocess or rebuild a Sense context while a run is in progress.
set -uo pipefail
cd "$(dirname "$0")/.."
export PYTHONPATH="$PWD"
unset LEADERBOARD_MODE LEADERBOARD_AGENT_MODEL LEADERBOARD_TRACK LLM_ROUTING_FILE BIRD_LLM_DUMP_DIR SYSTEM_AGENT_MAX_TOKENS DISABLE_AGGREGATES
export ENVIRONMENT_BACKENDS_FILE=config/environment_backends.snowflake_vs_0910.yaml
PY=.venv-adk/bin/python
SCEN="${1:?usage: run_snowflake_scenario.sh <1|2|3|cortex-sense-raw|cortex-sense-coco-views|cortex-sense-atscale-views|smoke>}"
if [ "$SCEN" = smoke ]; then BACKEND=sf_cortex_sense_smoke; LABEL="Wiring test (build role, not a scored run)"
else
  BACKEND=$($PY -c "from shared.environment_backends import resolve_snowflake_scenario as r; print(r('$SCEN'))") || exit 2
  LABEL=$($PY -c "from shared.environment_backends import SNOWFLAKE_SCENARIO_LABELS as L; print(L['$BACKEND'])")
fi
OUT=results/${BACKEND}_vs_0910; LOGD=logs/${BACKEND}_vs_0910; mkdir -p "$OUT" "$LOGD"
LOG="$LOGD/$BACKEND.log"
BASE='results/full0910_atscale_run0[123]_*.json'
step(){ echo; echo "=== $(date +%H:%M:%S) $* ==="; }
port(){ grep -E "^$1=" .env | tail -1 | cut -d= -f2; }

step "$LABEL (backend $BACKEND)"
step "preflight"
[ "$(git diff --quiet -- scripts/gen_snowflake_backends.py config/environment_backends.dbx_vs_0910.yaml; echo $?)" = 0 ] || echo "  note: generator or source config has uncommitted changes"
SA=$(port SYSTEM_AGENT_PORT); echo "  service ports: $SA $(port USER_SIM_PORT) $(port DB_ENV_PORT)"
[ -n "$SA" ] && [ "$SA" != "6000" ] || { echo "REFUSING: set this checkout's .env ports off the shared 6000-6002"; exit 1; }
ls $BASE >/dev/null 2>&1 || { echo "REFUSING: baseline files missing: $BASE"; exit 1; }
dscacheutil -q host -a name api.anthropic.com | grep -q ip_address || { echo "REFUSING: api.anthropic.com does not resolve"; exit 1; }
s=$(docker inspect -f '{{.State.Status}}' bird_interact_postgresql_full 2>/dev/null); echo "  BIRD postgres: $s"; [ "$s" = running ] || exit 1
BACKEND=$BACKEND $PY - <<'PYEOF' || exit 1
import asyncio, json, os
from shared.config import settings
from shared.environment_backends import get_backend_config, get_configured_domains, get_domain_config
from shared.snowflake_auth import resolve_token
from shared.snowflake_sql import client_for
from system_agent.tools_cortex_sense import _run_with_retry, parse_response, request_body

b = os.environ["BACKEND"]
cfg = get_backend_config(b)
doms = sorted(get_configured_domains(b))
assert len(doms) == 22, f"{len(doms)} domains configured, expected 22"
d0 = get_domain_config(b, doms[0])
sf = client_for(d0)                      # everything below runs AS THE SCENARIO'S ROLE
r = sf.execute("SELECT CURRENT_ROLE(), CURRENT_USER(), CURRENT_SECONDARY_ROLES()")
assert not r.error, f"REFUSING: cannot connect as {cfg['role']} with {cfg['token_env']}: {r.error}"
role, user, secondary = r.rows[0]
print(f"  running as role {role}, user {user}, secondary roles {secondary}")
assert role == cfg["role"], f"REFUSING: the token's role is {role}, the backend expects {cfg['role']}"
smoke = b == "sf_cortex_sense_smoke"
if not smoke:
    sec = json.loads(secondary) if isinstance(secondary, str) else (secondary or {})
    assert not (sec.get("roles") or "").strip(), f"REFUSING: secondary roles are active ({sec.get('roles')}); they would widen what the agent can read"
r = sf.execute("SELECT COUNT(DISTINCT TABLE_SCHEMA), COUNT(*) FROM BIRD_BENCH.INFORMATION_SCHEMA.TABLES WHERE TABLE_TYPE='BASE TABLE'")
assert not r.error, r.error
print("  BIRD_BENCH base tables visible:", r.rows[0][1], "in", r.rows[0][0], "schemas")
assert tuple(r.rows[0]) == (22, 244), "REFUSING: the role must see the 244 base tables of BIRD_BENCH"
# Semantic views the role can see. Other teams' views granted to PUBLIC (databases DEMO, QT, ...) are visible to
# every role on this shared account; they are in no Sense context and a submission reading one is refused. What
# must be exact is the set inside our own databases: none for scenario 1, only the scenario's own schemas otherwise.
views = sf.execute("SHOW SEMANTIC VIEWS IN ACCOUNT")
assert not views.error, views.error
cols = [c[0].lower() for c in views.columns]
ours = [(r_[cols.index("database_name")], r_[cols.index("schema_name")]) for r_ in views.rows
        if r_[cols.index("database_name")].upper().startswith("BIRD")]
print("  semantic views visible to the role:", len(ours), "in BIRD* databases,", len(views.rows) - len(ours), "elsewhere (PUBLIC grants)")
want_views = d0.get("views_schema")
if not smoke and not want_views:
    assert not ours, f"REFUSING: scenario 1's role can see {len(ours)} semantic views in BIRD* databases"
if not smoke and want_views:
    prefix = want_views.rsplit("_" + d0["schema"], 1)[0] + "_"
    other = sorted({f"{d_}.{s_}" for d_, s_ in ours if d_ != d0["views_catalog"] or not s_.startswith(prefix)})
    assert ours and not other, f"REFUSING: the role must see only {d0['views_catalog']}.{prefix}* semantic views; also sees {other[:5]}"
if not smoke:
    leak = sf.execute("SELECT 1 FROM BIRD_SENSE.BUILD_INPUTS.KNOWLEDGE_BASE LIMIT 1")
    assert leak.error, "REFUSING: the role can read the build inputs (BIRD_SENSE.BUILD_INPUTS)"
    old = sf.execute('SELECT 1 FROM BIRD."solar_panel"."plants" LIMIT 1')
    print("  old database BIRD readable by the role:", "no" if old.error else "YES (PUBLIC grant; submissions reading it are refused)")
# every database's context exists and returns documents for this role
listing = sf.execute("SELECT SYSTEM$CORTEX_AGENT_CORTEX_CONTEXT_BUILDER('{\"action\":\"list-contexts\"}')")
assert not listing.error, f"REFUSING: the role cannot list Cortex Sense contexts: {listing.error}"
have = {f"{c['database_name']}.{c['schema_name']}.{c['name']}": int(c["id"])
        for c in json.loads(listing.rows[0][0])["response_structured"].get("cortex_contexts", [])}
missing = [get_domain_config(b, d)["context"] for d in doms if get_domain_config(b, d)["context"] not in have]
assert not missing, f"REFUSING: {len(missing)} Cortex Sense contexts not found, e.g. {missing[:3]}"
print("  Cortex Sense contexts:", len(doms), "of", len(doms), "found")
# the lookup returns documents for this role, and one inline agent run completes as the role
cid = have[d0["context"]]
probe = sf.execute("SELECT SYSTEM$CORTEX_AGENT_CORTEX_CONTEXT('{\"request_structured\": {\"query\": \"%s tables\", \"cortex_context_ids\": [%d], \"max_results\": 20}}')" % (doms[0].replace("_", " "), cid))
assert not probe.error, f"REFUSING: the role cannot query its Cortex Sense context: {probe.error}"
docs = json.loads(probe.rows[0][0])["response_structured"].get("documents") or []
print(f"  context lookup ({d0['context']}):", len(docs), "documents")
assert docs, "REFUSING: the Cortex Sense lookup returned no documents for this role"
body = request_body(d0, [{"role": "user", "content": [{"type": "text", "text": f"In the {d0['catalog']}.{d0['schema']} database: which table has the most rows? Answer with one query."}]}])
turn = parse_response(asyncio.run(_run_with_retry(settings.snowflake_host.rstrip('/'), resolve_token(d0.get('token_env')), body)))
print("  agent run:", len(turn["context_docs"]), "context documents,", len(turn["sql_items"]), "statement(s),", len(turn["answer"]), "chars of answer")
assert turn["answer"] or turn["sql_items"], "REFUSING: the inline Cortex agent returned nothing for this role"
PYEOF

step "services"
bash scripts/start_services_isolated.sh || exit 1
H=$(curl -s "http://127.0.0.1:$SA/health"); echo "$H"
echo "$H" | grep -q '"model":"anthropic/claude-sonnet-5"' || { echo "REFUSING: agent is not Sonnet 5"; exit 1; }
echo "$H" | grep -q '"leaderboard_mode":false' || { echo "REFUSING: leaderboard mode on"; exit 1; }
[ -f "$LOG" ] && mv "$LOG" "$LOG.prev-$(date +%Y%m%d_%H%M%S)"

step "live comparison every 10 minutes"
( while sleep 600; do
    awk '/=== repetition [0-9]+ of [0-9]+ ===/{buf=""; rep=$0} {buf=buf $0 "\n"} END{printf "%s", buf}' "$LOG" > "$OUT/live_rep.log"
    $PY scripts/compare_vs_baseline_runs.py --log "$OUT/live_rep.log" --baseline "$BASE" --audit results/grading_audit.jsonl --backend "$BACKEND" > "$OUT/live_compare.tmp" 2>/dev/null \
      && { echo "updated $(date '+%Y-%m-%d %H:%M') $(grep -o 'repetition [0-9]* of [0-9]*' "$OUT/live_rep.log" | tail -1)"; cat "$OUT/live_compare.tmp"; } > "$OUT/live_compare.txt"
  done ) &
WATCH=$!

EXTRA=()
[ -n "${DATABASES:-}" ] && EXTRA+=(--databases "$DATABASES")
[ -n "${LIMIT:-}" ] && EXTRA+=(--limit "$LIMIT")
step "$BACKEND: Query tasks ${DATABASES:+of $DATABASES }${LIMIT:+(limit $LIMIT) }concurrency ${CONCURRENCY:-3}, ${REPEAT:-1} repetition(s)"
$PY -m orchestrator.runner --mode a-interact --backend "$BACKEND" --query-only --concurrency "${CONCURRENCY:-3}" --repeat "${REPEAT:-1}" \
    ${EXTRA[@]+"${EXTRA[@]}"} --output "$OUT/$BACKEND.json" > "$LOG" 2>&1
rc=$?
pkill -P $WATCH 2>/dev/null; kill $WATCH 2>/dev/null   # the watcher and its sleep, which would hold a piped stdout open
echo "  runner exit $rc; files: $(ls -1 $OUT/${BACKEND}_*.json 2>/dev/null | tr '\n' ' ')"
grep -E "^Done!|Avg Reward" "$LOG" | tail -3

step "final comparison (each repetition)"
FILES=$(ls -1tr $OUT/${BACKEND}_*.json 2>/dev/null | tail -${REPEAT:-1})
for R in $FILES; do
  tag=$(basename "$R" .json | grep -o '_run[0-9][0-9]' || true)
  echo "--- $R"
  $PY scripts/compare_vs_baseline_runs.py --results "$R" --baseline "$BASE" --audit results/grading_audit.jsonl | tee "$OUT/final_compare${tag}.txt"
done
bash scripts/start_services_isolated.sh --stop
