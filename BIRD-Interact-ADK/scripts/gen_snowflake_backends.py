"""Generate config/environment_backends.snowflake_vs_0910.yaml: the Databricks comparison file
(environment_backends.dbx_vs_0910.yaml) plus the Snowflake backends.

The Snowflake instruction is the Genie One raw-data instruction (dbx_genie_ontology_no_mv) with
only the tool-specific words rewritten (Genie -> Cortex, ask_genie -> ask_cortex, the database
prefix), exactly as that one was derived from the 2026-09-10 AtScale instruction. Rerun after any
change to the source block; never edit the generated blocks by hand.

    .venv-adk/bin/python scripts/gen_snowflake_backends.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "config" / "environment_backends.dbx_vs_0910.yaml"
DST = ROOT / "config" / "environment_backends.snowflake_vs_0910.yaml"

text = SRC.read_text()
a = text.index("  dbx_genie_ontology_no_mv:")
b = text.index("\n  #", text.index("    domains:", a))          # the comment that opens the next backend
block = text[a:b]
head, domains = block.split("    domains:\n", 1)
dbs = re.findall(r"^      (\w+):$", domains, re.M)
assert len(dbs) == 22, dbs

instruction = head[head.index("    instruction: |"):]
for old, new in (
    ("Genie - Databricks' natural-language data agent, grounded in the Genie Ontology of the user's Databricks workspace -",
     "Cortex - Snowflake's natural-language data agent, a Cortex Agent grounded in the Cortex Sense context of the user's database -"),
    ('"In the bird.<database> database: <the user\'s question>"', '"In the BIRD_BENCH.<DATABASE> database: <the user\'s question>"'),
    ("ask_genie", "ask_cortex"), ("GENIE", "CORTEX"), ("Genie", "Cortex"),
):
    assert old in instruction, old
    instruction = instruction.replace(old, new)
assert not re.search(r"genie|databricks|ontology|bird\.", instruction, re.I), "a Genie-specific phrase survived"


def backend(name, comment, role, token_env, views=None, context_suffix=""):
    out = [comment.rstrip(), f"  {name}:",
           "    tools_module: system_agent.tools_cortex_sense",
           "    tools_factory: get_ainteract_tools_cortex_sense",
           "    executor: snowflake", f"    role: {role}", f"    token_env: {token_env}",
           "    dialect: snowflake", "    agent_model: auto", "    error_hints: []",
           "    tool_costs:", "      ask_cortex: 1.0", "    small_action_costs:", "      ask_cortex: 0.5",
           "    leaderboard_tool_costs: {}", instruction.rstrip(), "    domains:"]
    for db in dbs:
        D = db.upper()
        out += [f"      {db}:", "        catalog: BIRD_BENCH", f"        schema: {D}", "        objects: tables",
                f"        context: BIRD_SENSE.CONTEXTS.BIRD_BENCH_{D}{context_suffix}"]
        if views:
            out += ["        views_catalog: BIRD_SENSE", f"        views_schema: {views}_{D}"]
    return "\n".join(out) + "\n"


blocks = [
    backend("sf_cortex_sense_raw", """
  # ── Snowflake scenarios (2026-11-20): the three Genie One setups repeated on Snowflake. The BIRD agent hands
  # every question to a Cortex Agent grounded in the database's Cortex Sense context (system_agent/
  # tools_cortex_sense.py) and submits the SQL it ran. Generated by scripts/gen_snowflake_backends.py.
  # Scenario 1: Cortex Sense on raw data, no Semantic Views. Role BIRD_S1: the 244 base tables of BIRD_BENCH.""",
            "BIRD_S1", "SNOWFLAKE_TOKEN_S1"),
    backend("sf_cortex_sense_coco_views", """
  # Scenario 2: Cortex Sense + the 83 Semantic Views Cortex Code authored (BIRD_SENSE.COCO_<DB>,
  # bird-snowflake-models/coco_semantic_views). Role BIRD_S2: the base tables and those views. Its contexts
  # (BIRD_BENCH_<DB>_COCO, which index the views too) are NOT BUILT YET.""",
            "BIRD_S2", "SNOWFLAKE_TOKEN_S2", views="COCO", context_suffix="_COCO"),
    backend("sf_cortex_sense_atscale_views", """
  # Scenario 3: Cortex Sense + Semantic Views generated from the AtScale SML models (BIRD_SENSE.ATSCALE_<DB>).
  # Role BIRD_S3. Neither the views nor the contexts (BIRD_BENCH_<DB>_ATSCALE) are built yet.""",
            "BIRD_S3", "SNOWFLAKE_TOKEN_S3", views="ATSCALE", context_suffix="_ATSCALE"),
    backend("sf_cortex_sense_smoke", """
  # WIRING TESTS ONLY, never a scored run: scenario 1's setup run as the build role BIRD_SENSE_PILOT, which
  # can also read the semantic views and the build inputs.""",
            "BIRD_SENSE_PILOT", "SNOWFLAKE_TOKEN_PILOT"),
]
header = ("# environment_backends.snowflake_vs_0910.yaml (2026-11-20): environment_backends.dbx_vs_0910.yaml plus the\n"
          "# Snowflake backends sf_cortex_sense_*. GENERATED by scripts/gen_snowflake_backends.py: edit the source\n"
          "# file or the generator, not this file.\n")
DST.write_text(header + text.rstrip("\n") + "\n" + "".join(blocks))
print("wrote", DST.name, "databases:", len(dbs), "instruction chars:", len(instruction))
