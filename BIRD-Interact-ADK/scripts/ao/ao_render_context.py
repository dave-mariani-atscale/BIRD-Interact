"""Export the AO semantic layer for one database and render three F1 input files.

Usage (from the AO repo): uv run python <ADK>/scripts/ao/ao_render_context.py <db_name> <out_dir>

Writes export.yaml (raw dump) plus:
  ao_terms.md           Terms: description, tables, column attributes
  ao_joins.md           semantic FK join groups, engine-declared vs AO-inferred
  ao_sql_attributes.md  SqlAttributes: term, name, expression, description
Firewall: an SqlAttribute's source statement (the harvested agent SQL) is kept
in export.yaml only; the rendered file carries the mined expression, never it.
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

import yaml

from auto_ontology.env import load_env

load_env()

from auto_ontology.dal import schema as s  # noqa: E402
from auto_ontology.dal.attributes import fetch_semantic_fk_join_groups  # noqa: E402
from auto_ontology.dal.model_interchange import fetch_export_rows  # noqa: E402
from auto_ontology.dal.session import store  # noqa: E402
from sqlalchemy import select  # noqa: E402

HEADER = (
    "<!-- Auto Ontology (AO) output for {db}: mined from the warehouse catalog, "
    "BIRD column meanings and a query log. Generated by scripts/ao/ao_render_context.py. -->\n\n"
)


def main(db: str, out_dir: str) -> None:
    out = Path(out_dir)
    db_id = store().query_read(
        select(s.catalog_database.c.id).where(s.catalog_database.c.name == db)
    )[0]["id"]
    rows = fetch_export_rows([db_id])
    groups = fetch_semantic_fk_join_groups(db)
    (out / "export.yaml").write_text(
        yaml.safe_dump(
            json.loads(json.dumps({"export": rows, "semantic_fk_join_groups": groups}, default=str)),
            sort_keys=False,
        )
    )

    tables = {}
    cols = {}
    for r in rows["catalog"]:
        tables[str(r["table_id"])] = (r["table_name"], r["table_description"])
        cols[str(r["column_id"])] = f'{r["table_name"]}.{r["column_name"]}'

    head = HEADER.format(db=db)
    terms = {str(t["id"]): t["name"] for t in rows["terms"]}

    # (a) terms
    lines = [head, f"# AO Terms ({len(rows['terms'])})\n"]
    for t in sorted(rows["terms"], key=lambda t: t["name"]):
        lines.append(f"\n## {t['name']}\n\n{t['description'].strip()}\n")
        reps = [tables[str(i)][0] for i in t["represents"] if str(i) in tables]
        if reps:
            lines.append(f"\nTables: {', '.join(sorted(set(reps)))}\n")
        attrs = sorted(t["columns_attributes"], key=lambda a: cols.get(str(a["column_id"]), ""))
        if attrs:
            lines.append("\n| attribute | source column | description |\n|---|---|---|\n")
            for a in attrs:
                desc = " ".join(a["description"].split()).replace("|", "\\|")
                lines.append(f"| {a['name']} | {cols.get(str(a['column_id']), '?')} | {desc} |\n")
    (out / "ao_terms.md").write_text("".join(lines))

    # (b) joins
    declared = {(cols.get(str(f["source_column_id"])), cols.get(str(f["target_column_id"]))) for f in rows["foreign_keys"]}
    lines = [head, f"# AO join groups ({len(groups)} semantic FK edges; {len(declared)} engine-declared FKs)\n\n"]
    lines.append(
        "`engine-declared` = a Postgres FOREIGN KEY constraint; `AO-inferred` = mined by AO. "
        "`use_in_join_paths` = AO's chosen default when one source table has several candidate columns for the same target.\n\n"
    )
    lines.append("| source | target | origin | use_in_join_paths |\n|---|---|---|---|\n")
    seen = set()
    for g in groups:
        src = f"{g['source_table_name']}.{g['source_column_name']}"
        tgt = f"{g['target_table_name']}.{g['target_column_name']}"
        seen.add((src, tgt))
        origin = "engine-declared" if (src, tgt) in declared else "AO-inferred"
        lines.append(f"| {src} | {tgt} | {origin} | {g['use_in_join_paths']} |\n")
    missing = sorted(d for d in declared if d not in seen and None not in d)
    if missing:
        lines.append("\nEngine-declared FKs with no AO semantic edge:\n\n")
        lines += [f"- {a} → {b}\n" for a, b in missing]
    (out / "ao_joins.md").write_text("".join(lines))

    # (c) sql attributes, deduped (one row per attribute, not per source statement)
    by_term = defaultdict(dict)
    for a in rows["sql_attributes"]:
        by_term[terms.get(str(a["term_id"]), "?")][str(a["id"])] = a
    n = sum(len(v) for v in by_term.values())
    lines = [head, f"# AO SqlAttributes ({n})\n\nMined from query-log expressions. `source` = how AO produced it (e.g. suggested, bridge_table).\n"]
    for term in sorted(by_term):
        lines.append(f"\n## {term}\n\n| name | expression | source | description |\n|---|---|---|---|\n")
        for a in sorted(by_term[term].values(), key=lambda a: a["name"]):
            expr = " ".join(a["expression"].split()).replace("|", "\\|")
            desc = " ".join(a["description"].split()).replace("|", "\\|")
            lines.append(f"| {a['name']} | `{expr}` | {a['source']} | {desc} |\n")
    (out / "ao_sql_attributes.md").write_text("".join(lines))

    for f in ("ao_terms.md", "ao_joins.md", "ao_sql_attributes.md"):
        text = (out / f).read_text()
        print(f"{f}: {len(text)} chars ≈ {len(text) // 4} tokens")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
